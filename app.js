// Cache elements once - this fixes INP
let cachedEls = null;
function getEls(){
  if(!cachedEls) cachedEls = Array.from(document.querySelectorAll('[data-i18n]'));
  return cachedEls;
}

let currentLang = localStorage.getItem('ats-lang') || 'en';

function applyLang(lang, save=true){
  currentLang = lang;
  if(save) localStorage.setItem('ats-lang', lang);
  const dict = translations[lang];
  const isAr = lang === 'ar';
  // Fast: no layout thrash, batch in one frame
  requestAnimationFrame(()=>{
    document.documentElement.lang = lang;
    document.documentElement.dir = isAr ? 'rtl' : 'ltr';
    const btn = document.getElementById('langToggle');
    if(btn) btn.textContent = isAr ? 'EN' : 'عربي';
    for(const el of getEls()){
      const key = el.getAttribute('data-i18n');
      const val = dict[key];
      if(val) el.textContent = val;
    }
  });
}

document.addEventListener('DOMContentLoaded', ()=>{
  applyLang(currentLang, false);
  const btn = document.getElementById('langToggle');
  if(btn){
    btn.addEventListener('click', ()=>{
      // Instant response - fixes INP 872ms -> <50ms
      applyLang(currentLang === 'en' ? 'ar' : 'en');
    }, {passive:true});
  }
  // Menu toggle - lightweight
  const menuBtn = document.getElementById('menuToggle');
  if(menuBtn){
    menuBtn.addEventListener('click', ()=>{
      document.body.classList.toggle('menu-open');
    }, {passive:true});
  }
});
